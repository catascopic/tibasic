"""Declarative argument schema for @preparse, driven by real type annotations.

A @preparse function declares each parameter's parser by annotating it with a
type from the vocabulary below — either a real runtime type (TiList, TiMatrix,
TiString, Thunk) or a PEP 695 ``type`` alias (Real, Numeric, Vectorized, …):

    @preparse_func
    def gcd(a: VectorizedReal, b: VectorizedReal) -> float: ...

Each vocabulary entry is a unique, hashable object used as a key into _REGISTRY,
which maps it to a parse function and a "kind" that drives vectorization.  Two
aliases may resolve to the same underlying type (TiListReal and TiListComplex
both alias TiList) yet stay distinct objects, so they select distinct parsers.

@preparse reads the signature (see schema_from_signature) and builds a tuple of
ArgSpec values.  Optionality and arity fall out of the signature: a parameter
with a default is optional; a ``*args`` parameter is variadic.

Parse functions all share the shape ``parse(args: ArgParser) -> value``.  Value
parsers are generated by make_validator(require_X): parse a general expression
via ArgParser.expr(), then assert its calculator data type with an O(1) guard.
Variable/name/thunk parsers delegate to the matching ArgParser method.

Runtime imports are deliberately light (tiobjects, core, decorators); Environment
and ArgParser stay behind TYPE_CHECKING, so importing the vocabulary never drags
in the heavyweight parser/environment modules (avoiding import cycles).
"""
from __future__ import annotations

import inspect
from dataclasses import dataclass
from enum import Enum, auto
from operator import methodcaller
from typing import Any, Callable, TYPE_CHECKING

from tiobjects import (
	TiList, TiMatrix, TiString,
	require_num, require_real, require_list, require_real_list, require_complex_list,
	require_matrix, require_str, require_list_or_matrix,
	require_vectorizable, require_vectorizable_real, require_matrix_vectorizable,
)
from core import Variable, Thunk
from decorators import TiCall, vectorize, matrix_vectorize

if TYPE_CHECKING:
	from environment import Environment
	from parser import ArgParser


# ── Vocabulary: real types and PEP 695 aliases ────────────────────────────────
# Each name below is a unique, hashable object used as a key into _REGISTRY.  The
# calculator has only six runtime data types — Real, Complex, List, ComplexList,
# Matrix, String — and a vocabulary entry asserts exactly one shape of those.
# Refinements that are NOT true types (e.g. "is this an integer?") belong in the
# function body via require_int, not here.

# Scalars.
type Real = float
type Complex = complex
type Numeric = Real | Complex

# Aggregates.  TiList / TiMatrix / TiString are used directly as annotations.
type TiListReal = TiList        # list with no complex element
type TiListComplex = TiList     # list with at least one complex element
type ListOrMatrix = TiList | TiMatrix
type AnyValue = Any             # any value, parsed without a type guard (min/max)

# Vectorized slots.  The body only ever sees scalars, so the annotation type is a
# scalar; the alias's presence signals @preparse to wrap the function so it maps
# element-wise over a list (Vectorized / VectorizedReal) or list-or-matrix
# (MatrixVectorized).  The parse-time guard still accepts the aggregate.
type Vectorized = Numeric
type VectorizedReal = Real
type MatrixVectorized = Real

# Variable references.  All alias Variable but select different parse methods.
type NumericVar = Variable
type ListVar = Variable
type MatrixVar = Variable
type StringVar = Variable
type EquationVar = Variable
type AnyVar = Variable
type ListVarPrefixOptional = ListVar

# Names and environment.
type LabelName = str
type ProgramName = str
type Env = Environment          # injected from ArgParser.env; consumes no token


# ── Parse functions: parse(args: ArgParser) -> value ──────────────────────────

def make_validator(require: Callable) -> Callable:
	"""Build a value parser: parse a general expression, then assert its type."""
	return lambda args: require(args.expr())

parse_numeric           = make_validator(require_num)
parse_real              = make_validator(require_real)
parse_list              = make_validator(require_list)
parse_real_list         = make_validator(require_real_list)
parse_complex_list      = make_validator(require_complex_list)
parse_matrix            = make_validator(require_matrix)
parse_string            = make_validator(require_str)
parse_list_or_matrix    = make_validator(require_list_or_matrix)
parse_vectorized        = make_validator(require_vectorizable)
parse_vectorized_real   = make_validator(require_vectorizable_real)
parse_matrix_vectorized = make_validator(require_matrix_vectorizable)
parse_value             = methodcaller('expr')   # no guard

# Variable / name / thunk parsers delegate to the matching ArgParser method.
parse_thunk          = methodcaller('thunk')
parse_numeric_var    = methodcaller('numeric_var')
parse_list_var       = methodcaller('list_var')
parse_matrix_var     = methodcaller('matrix_var')
parse_string_var     = methodcaller('string_var')
parse_equation_var   = methodcaller('equation_var')
parse_any_var        = methodcaller('any_var')
parse_list_var_prefix_optional = methodcaller('list_var_prefix_optional')
parse_label_name     = methodcaller('label_name')
parse_program_name   = methodcaller('program_name')


# ── Kind and Arity enums ──────────────────────────────────────────────────────

class _Kind(Enum):
	"""Drives vectorization wrapping in PreparsedFunc (see _REGISTRY)."""
	VALUE  = auto()   # plain value: no wrapping
	ENV    = auto()   # inject ArgParser.env; no token consumed
	VEC    = auto()   # element-wise over TiList (and scalars)
	MATVEC = auto()   # element-wise over TiMatrix or TiList (and scalars)


class _Arity(Enum):
	"""Parameter cardinality within a PreparsedFunc schema."""
	NORMAL   = auto()   # exactly one argument, required
	OPTIONAL = auto()   # one argument or absent; core default applies
	VARIADIC = auto()   # zero or more; greedily consumes remaining tokens


# ── Registry: vocabulary object → (parse function, kind) ──────────────────────
# `kind` is consumed once by @preparse to decide how (if at all) to wrap the core
# for vectorization.  env injects with no parse function (None).

_REGISTRY = {
	Numeric:               (parse_numeric, _Kind.VALUE),
	Real:                  (parse_real, _Kind.VALUE),
	TiList:                (parse_list, _Kind.VALUE),
	TiListReal:            (parse_real_list, _Kind.VALUE),
	TiListComplex:         (parse_complex_list, _Kind.VALUE),
	TiMatrix:              (parse_matrix, _Kind.VALUE),
	TiString:              (parse_string, _Kind.VALUE),
	ListOrMatrix:          (parse_list_or_matrix, _Kind.VALUE),
	AnyValue:              (parse_value, _Kind.VALUE),
	Vectorized:            (parse_vectorized, _Kind.VEC),
	VectorizedReal:        (parse_vectorized_real, _Kind.VEC),
	MatrixVectorized:      (parse_matrix_vectorized, _Kind.MATVEC),
	Thunk:                 (parse_thunk, _Kind.VALUE),
	NumericVar:            (parse_numeric_var, _Kind.VALUE),
	ListVar:               (parse_list_var, _Kind.VALUE),
	MatrixVar:             (parse_matrix_var, _Kind.VALUE),
	StringVar:             (parse_string_var, _Kind.VALUE),
	EquationVar:           (parse_equation_var, _Kind.VALUE),
	AnyVar:                (parse_any_var, _Kind.VALUE),
	ListVarPrefixOptional: (parse_list_var_prefix_optional, _Kind.VALUE),
	LabelName:             (parse_label_name, _Kind.VALUE),
	ProgramName:           (parse_program_name, _Kind.VALUE),
	Env:                   (None, _Kind.ENV),
}


# ── ArgSpec and schema extraction ─────────────────────────────────────────────

@dataclass(frozen=True)
class ArgSpec:
	"""One parsed parameter: how to read its value, plus arity/kind metadata."""
	parse: Any                      # Callable[[ArgParser], value]; None ⇒ inject env
	kind: _Kind = _Kind.VALUE       # drives vectorization wrapping (see PreparsedFunc)
	arity: _Arity = _Arity.NORMAL   # NORMAL / OPTIONAL / VARIADIC

	def __repr__(self):
		name = 'env' if self.parse is None else getattr(self.parse, '__name__', 'parse')
		flags = {_Arity.OPTIONAL: '?', _Arity.VARIADIC: '*'}.get(self.arity, '')
		return f"{name}{flags}"


def schema_from_signature(func) -> tuple:
	"""Build an ArgSpec schema from *func*'s annotated parameters.

	Each parameter must be annotated with a vocabulary type.  A parameter with a
	default becomes optional; a ``*args`` parameter becomes variadic.  The return
	annotation is ignored.

	Annotations are read with ``eval_str=True`` so this works whether or not the
	defining module uses ``from __future__ import annotations`` — the vocabulary
	names just have to be importable there (they are).
	"""
	annotations = inspect.get_annotations(func, eval_str=True)
	schema = []
	for name, p in inspect.signature(func).parameters.items():
		if name not in annotations:
			raise TypeError(f"@preparse: {func.__name__}: parameter {name!r} has no annotation")
		ann = annotations[name]
		try:
			parse, kind = _REGISTRY[ann]
		except (KeyError, TypeError):
			raise TypeError(
				f"@preparse: {func.__name__}: parameter {name!r} has unknown arg type {ann!r}"
			)
		if p.kind is inspect.Parameter.VAR_POSITIONAL:
			arity = _Arity.VARIADIC
		elif p.default is not inspect.Parameter.empty:
			arity = _Arity.OPTIONAL
		else:
			arity = _Arity.NORMAL
		schema.append(ArgSpec(parse, kind, arity))
	return tuple(schema)


# ── @preparse ─────────────────────────────────────────────────────────────────

class Finalize(Enum):
	"""Which ArgParser end method PreparsedFunc calls after parsing.

	  FUNC      — end_func()       expression functions; eats ), no separator
	  CMD       — end_cmd()        no-paren commands; eats trailing separator
	  CMD_FUNC  — end_paren_cmd()  paren commands; eats ) + separator
	  NONE      — (nothing)        leaves the parser untouched so the command
	                               bunches with whatever follows (e.g. DelVar)
	"""
	FUNC = auto()
	CMD = auto()
	CMD_FUNC = auto()
	NONE = auto()


# Maps each Finalize mode to the ArgParser end method name (None = no call).
_END_METHOD = {
	Finalize.FUNC: 'end_func',
	Finalize.CMD: 'end_cmd',
	Finalize.CMD_FUNC: 'end_paren_cmd',
	Finalize.NONE: None,
}


class PreparsedFunc(TiCall):
	"""Wraps a plain core function with a declarative arg schema (see module docs).

	The schema is read from the core's type annotations.  Each parse method guards
	its argument's true type at the token boundary, so the core needs no value
	validation wrapper — vectorization (if any) is the only wrapper:

	  * if any parameter is Vectorized/VectorizedReal, the core is wrapped in
	    @vectorize (maps element-wise over a TiList in any such slot);
	  * if a parameter is MatrixVectorized, the core is wrapped in
	    @matrix_vectorize (also maps over a TiMatrix).  At most one such parameter
	    is allowed, and it may not be combined with Vectorized parameters.

	The core stays a plain function, so functions remain callable from other Python
	code (composability) via TiCall.__call__.
	"""
	def __init__(self, core: Callable, end: Finalize = Finalize.FUNC) -> None:
		schema = schema_from_signature(core)
		kinds = [s.kind for s in schema]
		if _Kind.MATVEC in kinds:
			if kinds.count(_Kind.MATVEC) > 1:
				raise TypeError(f"{core.__name__}: at most one matrix-vectorized parameter allowed")
			if _Kind.VEC in kinds:
				raise TypeError(f"{core.__name__}: cannot mix matrix-vectorized and vectorized parameters")
			func = matrix_vectorize(core)
		elif _Kind.VEC in kinds:
			func = vectorize(core)
		else:
			func = core

		super().__init__(func)
		self.schema = schema
		self.end_method = _END_METHOD[end]

	def call_with_parser(self, a: ArgParser):
		args = a.take(*self.schema)
		if self.end_method is not None:
			getattr(a, self.end_method)()
		return a.env.guard_real(args, self.func(*args))


def preparse(end: Finalize | None = None):
	"""Return a decorator that wraps a core function as a PreparsedFunc.

	Prefer the named aliases below over calling this directly:
	  preparse_func     — expression functions  (end_func, eats `)`              )
	  preparse_cmd      — no-paren commands     (end_cmd, eats trailing separator)
	  preparse_cmd_func — paren commands        (end_paren_cmd, eats `) + sep`   )
	  preparse_bunch    — bunching commands     (no finalizer, e.g. DelVar       )

	Use this directly only when you need to select a Finalize mode dynamically.
	"""
	final_end = Finalize.FUNC if end is None else end

	def decorator(core: Callable) -> PreparsedFunc:
		return PreparsedFunc(core, end=final_end)
	return decorator


# Named decorator aliases — preferred over calling preparse() directly.
preparse_func     = preparse(Finalize.FUNC)
preparse_cmd      = preparse(Finalize.CMD)
preparse_cmd_func = preparse(Finalize.CMD_FUNC)
preparse_bunch    = preparse(Finalize.NONE)
